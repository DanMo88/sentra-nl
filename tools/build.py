#!/usr/bin/env python3
"""Build js/data.js + tools/tts_jobs.json for Sentra NL.
content/<lv>-<nn>.txt : "Dutch | Persian meaning | Persian-letter reading" (one reading token per Dutch word).
Sentence audio alternates female (odd global number) / male (even); word tiles use the word voice."""
import json, os, re, sys, glob, unicodedata
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["A1", "A2", "B1", "B2", "C1", "C2"]
ZW = "\u200c"
def fold(t):  # é→e, ë→e, ĳ/ÿ→ij  (must match wslug in js/app.js)
    t = t.replace("ĳ", "ij").replace("Ĳ", "IJ").replace("ÿ", "ij")
    return "".join(c for c in unicodedata.normalize("NFD", t) if unicodedata.category(c) != "Mn")
def slug(t): return re.sub(r"[^a-z0-9]+", "-", fold(t).lower()).strip("-")[:80].strip("-")
def bare(w):  # keep letters (incl. diacritics), apostrophe and hyphen inside the word (must match bareW in js/app.js)
    b = re.sub(r"[^\w'\-]|[\d_]", "", w).strip("-'")
    return b or re.sub(r"[^\w]|_", "", w)
def fa_fix(t):
    t = t.replace("~", ZW).replace("?", "؟").replace(",", "،").replace(";", "؛")
    return re.sub(r"\s+", " ", t).strip()
TITLES = {"a1-01": "سلام و آشنایی"}
def main():
    files = sorted(glob.glob(os.path.join(ROOT, "content", "*.txt")), key=lambda f: (ORDER.index(os.path.basename(f)[:2].upper()), f))
    lessons, jobs, n, errors, seen = [], {}, 0, [], {}
    for f in files:
        lid = os.path.basename(f)[:-4]; lv = lid[:2].upper(); num = int(lid[3:])
        rows = [[x.strip() for x in l.split("|")] for l in open(f, encoding="utf-8").read().splitlines() if l.strip() and not l.startswith("#")]
        out, n0 = [], n + 1
        for r in rows:
            if len(r) != 3: errors.append(f"{lid}: bad line {r}"); continue
            nl, fa, rd = r; n += 1
            k = re.sub(r"[^a-z]", "", fold(nl).lower())
            if k in seen: errors.append(f"{lid}: duplicate of {seen[k]}: {nl}")
            seen[k] = lid
            ws, rs = nl.split(), rd.split()
            if len(ws) != len(rs): errors.append(f"{lid}: token mismatch {nl} / {rd}")
            for w in ws:
                bw = bare(w)
                if not bw: errors.append(f"empty word in {nl!r}"); continue
                jobs.setdefault(f"audio/w-{slug(bw)}.mp3", {"text": bw, "voice": "w"})
            jobs[f"audio/s{n:04d}.mp3"] = {"text": nl, "voice": "f" if n % 2 else "m"}
            out.append([nl, fa_fix(fa), rd])
        lessons.append({"id": lid, "level": lv, "num": num, "title": TITLES.get(lid, lid), "n0": n0, "s": out})
    if errors: print("ERRORS:", *errors, sep="\n"); sys.exit(1)
    open(os.path.join(ROOT, "js", "data.js"), "w", encoding="utf-8").write(
        "/* generated by tools/build.py */\nwindow.SENTRA_LESSONS = " + json.dumps(lessons, ensure_ascii=False, separators=(",", ":")) + ";\n")
    json.dump(jobs, open(os.path.join(ROOT, "tools", "tts_jobs.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    print(len(lessons), "lessons", n, "sentences", len(jobs), "audio jobs")
main()
